import { Exercise, ExerciseType, Level, Muscle, Variant } from "../types";
function e(
  id: string,
  name: string,
  muscle: Muscle,
  priority: number,
  minLevel: Level = "beginner",
  type: ExerciseType = "isolation",
  variant: Variant = "machine",
  secondary: Muscle[] = [],
  note?: string,
): Exercise {
  return {
    id,
    name,
    muscle,
    priority,
    minLevel,
    type,
    variant,
    secondary,
    equipment: {
      machine: "Máquina específica",
      free: "Barra o mancuernas",
      cable: "Polea ajustable",
      smith: "Multipower",
    }[variant],
    range: type === "compound" ? [6, 8] : [8, 10],
    substitutions: [],
    note,
    pullPattern: muscle === "back" ? (id.includes("row") ? "horizontal" : id.includes("pulldown") ? "vertical" : undefined) : undefined,
    scoreEligible: variant === "free",
    // Total load increment for bars; per-dumbbell increment for dumbbells.
    loadStep: variant === "free" && !name.includes("mancuernas") ? 2.5 : 1.25,
  };
}
